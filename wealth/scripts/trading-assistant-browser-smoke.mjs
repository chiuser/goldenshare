  await page.getByRole("button", { name: "确认更正", exact: true }).click();
  await page.waitForFunction(() => !document.querySelector("dialog[open]"));
  // The backend commits successfully; only the browser's response is lost.
  // The UI must look up the request, never issue a second cash write.
  let lostResponseCount = 0;
  const cashPath = `**/accounts/${second}/cash-flows`;
  await page.route(cashPath, async route => {
    lostResponseCount += 1;
    const response = await route.fetch();
    assert.equal(response.status(), 201);
    await route.abort("failed");
  });
  await page.getByRole("button", { name: "资金转入/转出", exact: true }).click();
