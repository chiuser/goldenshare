  await page.getByRole("button", { name: "保存资金变动", exact: true }).click();
  await page.getByRole("button", { name: "返回编辑", exact: true }).click();
  await page.getByText("转出金额超过当前可用现金，请检查。", { exact: true }).waitFor();
  assert.equal(await page.getByLabel("金额（元）", { exact: false }).inputValue(), "2000.00");
  const errorStyle = await page.locator(".ta-field-error").first().evaluate(el => ({ fontSize: getComputedStyle(el).fontSize, lineHeight: getComputedStyle(el).lineHeight }));
  assert.deepEqual(errorStyle, { fontSize: "11px", lineHeight: "16px" });
  await page.screenshot({ path: output + "-cash-error.png" });
  await fill("金额（元）", "100.00");
  await page.getByRole("button", { name: "保存资金变动", exact: true }).click();
  await page.getByRole("button", { name: "更正流水", exact: true }).click();
  await fill("金额（元）", "120.00");
  await page.getByRole("button", { name: "核对更正", exact: true }).click();
  await page.getByText("100.00 → 120.00", { exact: true }).waitFor();
  await page.screenshot({ path: output + "-cash-correction.png" });
  await page.getByRole("button", { name: "确认更正", exact: true }).click();
  await page.getByRole("button", { name: "作废流水", exact: true }).click();
  await page.getByRole("button", { name: "确认作废", exact: true }).click();
  await page.getByText("资金转出 · 已作废", { exact: true }).waitFor();
  await page.getByRole("button", { name: "关闭", exact: true }).last().click();
  await page.waitForFunction(() => !document.querySelector("dialog[open]"));
  await page.getByRole("button", { name: "记录买入", exact: true }).click();
  await fill("股票", "000001");
  await page.getByRole("listbox", { name: "股票搜索结果" }).getByRole("option").first().click();
  await fill("成交日期", "2026-09-11"); await fill("成交价格", "10.00"); await fill("成交数量", "13");
  await page.waitForFunction(() => [...document.querySelectorAll("input")].some(el => el.readOnly && el.value === "5.00"));
  await page.screenshot({ path: output + "-buy.png" });
