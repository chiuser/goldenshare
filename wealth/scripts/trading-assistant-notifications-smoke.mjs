// Real local API/M3/M6/M7; only the fixture's external Feishu transport is offline.
import assert from "node:assert/strict";
import { pathToFileURL } from "node:url";
const [base, output, modulePath] = process.argv.slice(2);
assert.equal(new URL(base).hostname, "127.0.0.1");
const { chromium } = await import(pathToFileURL(modulePath).href);
const browser = await chromium.launch({ headless:true });
const context = await browser.newContext({ viewport:{width:1600,height:1080} });
try {
  const session = await (await context.request.get(base + "/test-session")).json();
  assert.equal(session.fixture,"trading-assistant-isolated");
  const headers = {Authorization:"Bearer " + session.token}, root = base + "/api/v1/wealth/market/trading-assistant";
  await context.addInitScript(token=>localStorage.setItem("wealth.auth.access-token",token),session.token);
  const page = await context.newPage(), errors=[];
  let allowLostSave = false, lostSaveConsole = 0;
  page.on("pageerror",e=>errors.push(e.message));
  page.on("console",m=>{ if(m.type()==="error") {
    if (allowLostSave && m.text().includes("net::ERR_FAILED")) lostSaveConsole++;
    else errors.push(m.text());
  } });
  await page.goto(base + "/wealth/market/trading-assistant");
  await page.getByRole("button",{name:"计划与监控",exact:true}).click();
  await page.getByRole("button",{name:"通知设置",exact:true}).click();
  let dialog = page.getByRole("dialog").last();
  await dialog.getByLabel("自定义名称",{exact:false}).fill("浏览器验收机器人");
  await dialog.getByLabel("飞书机器人地址（Webhook）",{exact:false}).fill("https://open.feishu.cn/open-apis/bot/v2/hook/isolated-browser");
  const keywords = Array.from({length:11},(_,i)=>`词${i}`).join(",");
  await dialog.getByLabel(/自定义关键词/).fill(keywords);
  assert.equal(await dialog.getByLabel(/自定义关键词/).inputValue(),keywords);
  assert.equal(await dialog.getByRole("button",{name:"发送测试通知"}).isDisabled(),true);
  await dialog.getByText("最多填写 10 个关键词。",{exact:true}).waitFor();
  await page.screenshot({path:output+"-keyword.png",fullPage:true});
  await dialog.getByLabel(/自定义关键词/).fill("财势乾坤");
  await dialog.getByRole("button",{name:"发送测试通知"}).click();
  await dialog.getByRole("heading",{name:"测试发送成功",exact:true}).waitFor();
  await dialog.getByRole("button",{name:"返回修改",exact:true}).waitFor();
  const widths = await dialog.locator(".ta-dialog-footer button").evaluateAll(nodes=>nodes.map(n=>n.getBoundingClientRect().width));
  assert.ok(Math.abs(widths[0]-widths[1])<1);
  assert.equal(await dialog.evaluate(n=>Math.round(n.getBoundingClientRect().width)),640);
  await page.screenshot({path:output+"-confirmed.png",fullPage:true});
  await dialog.getByRole("button",{name:"已收到，保存并使用"}).click();
  await page.waitForFunction(()=>!document.querySelector("dialog[open]"));
  const config = await (await context.request.get(root+"/robot",{headers})).json();
  assert.equal(config.robot.name,"浏览器验收机器人");
  assert.ok(!JSON.stringify(config).includes("isolated-browser"));
  await page.getByRole("button",{name:/^独立提醒/}).click();
  await page.getByRole("button",{name:"新建独立提醒",exact:true}).click();
  dialog = page.getByRole("dialog").last();
  await dialog.getByRole("combobox",{name:"股票 *"}).fill("000001");
  await dialog.getByRole("option",{name:/测试股票/}).click();
  await dialog.getByLabel("截止日期",{exact:false}).fill("2026-09-14");
  await dialog.getByLabel("价格上限（元）").fill("10.00");
  await dialog.getByRole("button",{name:"浏览器验收机器人"}).waitFor();
  await dialog.getByRole("button",{name:"创建提醒",exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector("dialog[open]"));
  const list = await (await context.request.get(root+"/alerts",{headers})).json();
  assert.equal(list.items.length,1);
  const ruleId = list.items[0].ruleId;
  await context.request.post(base+"/test-notification-outcome?state=FAILED");
  await context.request.post(base+"/test-rule-clock?at="+encodeURIComponent("2026-09-14T16:00:00+08:00"));
  let detail; const until=Date.now()+45000;
  while(Date.now()<until) {
    const response = await context.request.get(root+"/alerts/"+ruleId,{headers}); assert.ok(response.ok(),await response.text());
    detail=await response.json(); if(detail.notificationSummary.state==="FAILED") break;
    await new Promise(resolve=>setTimeout(resolve,150));
  }
  assert.equal(detail.notificationSummary.state,"FAILED",JSON.stringify(detail));
  await page.goto(base+"/wealth/market/trading-assistant?ruleType=ALERT&ruleId="+ruleId);
  await page.getByRole("button",{name:"查看通知记录"}).click();
  await page.getByRole("heading",{name:"第 1 次 · 发送失败",exact:true}).waitFor();
  await page.screenshot({path:output+"-failed.png",fullPage:true});
  await context.request.post(base+"/test-notification-outcome?state=SUCCEEDED");
  await page.getByRole("button",{name:"重试失败通知"}).click();
  await page.getByRole("button",{name:"确认重试",exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll("dialog[open]").length===2);
  const retryUntil = Date.now()+15000;
  let notification;
  while(Date.now()<retryUntil) {
    const response=await context.request.get(root+"/notifications/"+detail.notificationSummary.notificationId,{headers});
    assert.ok(response.ok(),await response.text()); notification=await response.json();
    if(notification.state==="SUCCEEDED") break;
    await new Promise(resolve=>setTimeout(resolve,100));
  }
  assert.equal(notification.state,"SUCCEEDED",JSON.stringify(notification));
  await page.getByRole("button",{name:"刷新状态",exact:true}).click();
  await page.getByRole("heading",{name:"第 2 次 · 发送成功",exact:true}).waitFor();
  assert.equal(await page.getByRole("button",{name:"重试失败通知"}).count(),0);
  await page.screenshot({path:output+"-history.png",fullPage:true});
  await page.getByRole("dialog").last().locator(".ta-dialog-footer").getByRole("button",{name:"关闭",exact:true}).click();
  await page.getByRole("button",{name:"返回列表",exact:true}).click();
  await context.request.post(base+"/test-notification-outcome?state=SUCCEEDED");
  await page.getByRole("button",{name:"通知设置",exact:true}).click();
  dialog = page.getByRole("dialog").last();
  await dialog.getByLabel(/自定义名称/).fill("实际已保存的新名称");
  await dialog.getByRole("button",{name:"发送测试通知",exact:true}).click();
  await dialog.getByRole("button",{name:"已收到，保存并使用",exact:true}).waitFor();
  let confirmationWrites = 0;
  allowLostSave = true;
  await page.route("**/robot/candidates/*/confirmations", async route => {
    confirmationWrites++;
    const response = await route.fetch(); assert.equal(response.status(),200);
    await route.abort("failed");
  });
  await dialog.getByRole("button",{name:"已收到，保存并使用",exact:true}).click();
  await dialog.getByRole("alert").filter({hasText:"本次保存未完成"}).waitFor();
  assert.equal(await dialog.getByLabel(/自定义名称/).count(),0);
  assert.equal(await dialog.getByRole("button",{name:/继续保存|恢复/}).count(),0);
  await page.screenshot({path:output+"-save-ended.png",fullPage:true});
  await dialog.getByRole("button",{name:"取消",exact:true}).click();
  await page.getByRole("button",{name:"通知设置",exact:true}).click();
  dialog = page.getByRole("dialog").last();
  assert.equal(await dialog.getByLabel(/自定义名称/).inputValue(),"实际已保存的新名称");
  assert.equal(await dialog.getByLabel(/飞书机器人地址/).inputValue(),"");
  assert.equal(confirmationWrites,1); assert.equal(lostSaveConsole,1);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({robotConfigured:true,manualReceipt:true,keywordLimit:true,realTrigger:true,attempts:2,saveEnded:true,confirmationWrites,lostSaveConsole,consoleErrors:errors}));
} finally { await context.close(); await browser.close(); }
