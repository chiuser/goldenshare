def test_async_request_cancel_reaches_existing_connection_close_and_no_pending_tasks(monkeypatch):
    # Existing fixture mirrors verified psycopg local close/NullPool semantics.
    from tests.test_index_detail_daily_wave_connection import environment
    events = environment(monkeypatch, sql_delay=.4, local_yield=True)
    owners = []
    def factory(*, budget):
        instance = connection_module.DailyWaveReadSession(budget=budget,
            database_url="postgresql+psycopg://reader:secret@test.invalid/db")
        owners.append(instance)
        return instance
    endpoint = make_app(factory=factory).routes[-1].endpoint
    async def run():
        request = Request(dict(type="http",method="GET",path=PATH,query_string=b"tsCode=000001.SH",headers=[]))
        task = asyncio.create_task(endpoint(request,_ts_code="000001.SH",_user=None))
        while not any(isinstance(item,tuple) and item[0]=="execute" for item in events):
            await asyncio.sleep(0)
        task.cancel("api-stop")
        with pytest.raises(asyncio.CancelledError) as caught: await task
        assert caught.value.args == ("api-stop",)
        assert owners[0].closed and events.count("rollback") == 0
        assert events.index("raw.close") < events.index("sql.cancelled")
        for name in ("raw.close","invalidate","session.close","connection.close","dispose"):
            assert name+".done" in events
        assert not [t for t in asyncio.all_tasks() if t is not asyncio.current_task() and not t.done()]
    asyncio.run(run())


