class Clock:
    now = 0.0


def fake_clock(monkeypatch):
    clock = Clock()
    # Replace this module's time reference, never global asyncio/event-loop time.
    monkeypatch.setattr(budget_module, "time", SimpleNamespace(monotonic=lambda: clock.now))
    return clock


@pytest.mark.parametrize("stage", ["projection", "validate", "dump", "encode", "response"])
@pytest.mark.parametrize("duration,expected", [(.1,200),(.2,503),(.3,503)])
def test_original_deadline_covers_each_response_stage_and_exact_boundary(monkeypatch, stage, duration, expected):
    clock = fake_clock(monkeypatch)
    class Result(LiteralResult):
        def to_dict(self):
            payload = super().to_dict()
            if stage == "projection": clock.now += duration
            return payload
    real_model = DailyWaveReadyDto
    class Model:
        @staticmethod
        def model_validate(payload, *, strict):
            model = real_model.model_validate(payload, strict=strict)
            if stage == "validate": clock.now += duration
            class Validated:
                def model_dump(self, **kwargs):
                    result = model.model_dump(**kwargs)
                    if stage == "dump": clock.now += duration
                    return result
            return Validated()
    monkeypatch.setattr(module, "DailyWaveReadyDto", Model)
    real_dumps = json.dumps
    def encode(*args, **kwargs):
        result = real_dumps(*args, **kwargs)
        if stage == "encode": clock.now += duration
        return result
    monkeypatch.setattr(module, "json", SimpleNamespace(dumps=encode))
    real_response = module.Response
    def response(*args, **kwargs):
        result = real_response(*args, **kwargs)
        if stage == "response": clock.now += duration
        return result
    monkeypatch.setattr(module, "Response", response)
    async def build(self, **kwargs):
        assert kwargs["deadline"] == 8.0 and kwargs["spec"] is DEFAULT_SPEC
        assert kwargs["check_cancelled"]() is False
        clock.now = 7.8
        return Result()
    monkeypatch.setattr(module.DailyWaveQueryService, "build", build)
    # Decorator metadata must refer to the real DTO before its narrow stage spy.
    monkeypatch.setattr(module, "DailyWaveReadyDto", real_model)
    app = make_app()
    monkeypatch.setattr(module, "DailyWaveReadyDto", Model)
    with TestClient(app) as client:
        result = client.get(PATH + QUERY)
    assert result.status_code == expected and result.headers["cache-control"] == "no-store"
    if expected == 503: assert result.json()["code"] == "DAILY_WAVE_BUDGET_EXCEEDED"


