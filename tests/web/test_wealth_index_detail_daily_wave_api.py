class LiteralResult:
    """Source replacement shaped as the current ReviewResult.to_dict contract."""
    def __init__(self, payload=None):
        self.payload = deepcopy(ready_payload() if payload is None else payload)
        if self.payload.get("status") == "ready":
            self.payload["priceSegments"] = self.payload.pop("segments")
            self.payload["asofChanges"] = []

    def to_dict(self):
        return deepcopy(self.payload)


def no_source_factory(**kwargs):
    pytest.fail("an isolated route unexpectedly opened a source connection")


def make_app(*, factory=no_source_factory, auth=lambda: None):
    app = FastAPI()
    install_exception_handlers(app)
    app.include_router(module.build_router(session_factory=factory,
        auth_dependency=auth, error_factory=WebAppError), prefix="/api/v1")
    return app


def stub_build(monkeypatch, result=None, error=None):
    calls = []
    async def build(self, **kwargs):
        calls.append(kwargs)
        if error is not None:
            raise error
        return result if result is not None else LiteralResult()
    monkeypatch.setattr(module.DailyWaveQueryService, "build", build)
    return calls


@pytest.mark.parametrize("status", ["ready", "empty"])
def test_real_http_preserves_literal_fields_text_null_and_explicit_projection(monkeypatch, status):
    expected = ready_payload() if status == "ready" else empty_payload()
    source = LiteralResult(expected)
    calls = stub_build(monkeypatch, result=source)
    with TestClient(make_app()) as client:
        response = client.get(PATH + QUERY)
    assert response.status_code == 200 and response.json() == expected
    assert response.headers["cache-control"] == "no-store"
    assert response.headers["content-type"] == "application/json"
    assert int(response.headers["content-length"]) == len(response.content)
    assert "priceSegments" not in response.json() and "asofChanges" not in response.json()
    assert len(calls) == 1 and calls[0]["spec"] is DEFAULT_SPEC
    assert calls[0]["deadline"] > 0 and callable(calls[0]["check_cancelled"])
    if status == "ready":
        assert source.payload["priceSegments"] == [] and "asofChanges" in source.payload
        assert response.json()["pendingTurns"][0]["confirmedAt"] is None


