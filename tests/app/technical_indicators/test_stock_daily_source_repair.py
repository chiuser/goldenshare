def request(client, **params):
    return client.get(PATH, params={"tsCode": "600000.SH", "endDate": "2026-02-02", "debug": 1, **params})


def check_values(payload, days):
    assert [bar["tradeDate"] for bar in payload["bars"]] == [d.isoformat() for d in days]
    assert payload["meta"]["count"] == len(days)
    for bar in payload["bars"]:
        assert (bar["open"], bar["high"], bar["low"], bar["close"], bar["vol"], bar["amount"]) == (10, 10, 10, 10, 100, 1000)
        assert bar["factors"]["macd"] == {"dif": 0, "dea": 0, "macd": 0}
        assert bar["factors"]["kdj"] == {"k": 50, "d": 50, "j": 50}


@pytest.mark.parametrize("env", ["local", "prod"])
def test_environment_source_and_target_reuse(source_client, env):
    state = source_client
    with state.client_for(env) as client:
        response = request(client, limit=2, startDate="2026-01-30")
        assert response.status_code == 200, response.text
    payload = response.json()
    check_values(payload, DAYS[-2:])
    assert all(bar["factors"]["boll"] == {"upper": 10, "middle": 10, "lower": 10} for bar in payload["bars"])
    assert state.calculations[0]["statistics"].source_rows == 21
    if env == "local":
        assert not state.targets and not state.history
        assert [s[1] for s in state.scans] == [TARGET_FIELDS, HISTORY_FIELDS]
        paths = [p for scan in state.scans for p in scan[0]]
        assert len(paths) == len(set(paths)) == 21
        assert not state.scans[0][3] and state.scans[1][3]
        assert payload["debugInfo"]["sourceTables"] == ["core_serving.security_serving", "dg.silver_stock_factor_pro"]
    else:
        assert not state.scans and len(state.targets) == len(state.history) == 1
        assert state.history[0]["before"] == DAYS[-2] and state.history[0]["limit"] == 500
        assert payload["debugInfo"]["sourceTables"] == ["core_serving.security_serving", "core_serving.equity_factor_pro"]


def test_full_short_history_preserves_nulls(source_client):
    with source_client.client_for("dev") as client:
        response = request(client)
        assert response.status_code == 200, response.text
    payload = response.json()
    check_values(payload, DAYS)
    for bar in payload["bars"][:19]:
        assert bar["factors"]["ma"]["ma20"] is None
        assert bar["factors"]["boll"] == {"upper": None, "middle": None, "lower": None}
    assert [bar["factors"]["ma"]["ma20"] for bar in payload["bars"][19:]] == [10, 10]
    assert source_client.calculations[0]["statistics"].source_rows == 21


def test_dg_skips_unrelated_file(source_client):
    with source_client.client_for("dev") as client:
        response = request(client, endDate="2026-02-03", limit=1)
        assert response.status_code == 200, response.text
    check_values(response.json(), DAYS[-1:])
    assert source_client.calculations[0]["statistics"].source_rows == 21
    paths = [p for scan in source_client.scans for p in scan[0]]
    assert len(paths) == len(set(paths)) == 22


def test_empty_and_missing_source(source_client):
    with source_client.client_for("local") as client:
        response = request(client, endDate="1900-01-01")
        assert response.status_code == 200
        body = response.json()
        assert body["bars"] == [] and body["meta"]["count"] == 0
        assert body["dataStatus"]["status"] == "EMPTY"
        assert body["dataStatus"]["observedTradeDate"] is None
    with source_client.client_for("local", source_root=source_client.root / "absent") as client:
        with pytest.raises(SourceReadError, match="directory is unavailable"):
            request(client)
    assert not source_client.calculations and not source_client.targets and not source_client.history
