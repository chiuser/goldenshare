def bottom_wait_ledgers():
    """Literal bottom return: old waits at close99; new retains DULL against98/4."""
    source = list(INPUT[:10])
    source[6] = (DAYS[6], 96.0, 6.0, 7.0, -2.0, True)
    source[7] = (DAYS[7], 97.0, 5.0, 6.0, -2.0, True)
    source[8] = (DAYS[8], 99.0, 6.0, 7.0, -2.0, True)
    source[9] = (DAYS[9], 99.0, 5.8, 6.8, -2.0, True)
    waves = list(deepcopy(WAVES[:10]))
    waves[6] = wave(-1, 6, 6, 1, 96.0, 6.0, 6, 6)
    waves[7] = wave(-1, 6, 7, 2, 96.0, 5.0, 6, 7)
    waves[8] = wave(-1, 6, 8, 3, 96.0, 5.0, 6, 7)
    waves[9] = wave(-1, 6, 9, 4, 96.0, 5.0, 6, 7)
    ref = dict(startTime=DAYS[2], endTime=DAYS[3], price=98.0, dif=4.0)
    new_ref = {**ref, "priceAt": DAYS[2], "difAt": DAYS[3]}
    old, new = ledgers(length=10)
    for n in range(10):
        old["rows"][n]["input"] = dict(zip(("time", "close", "dif", "dea", "hist", "completed"), source[n]))
        for name in ("r2", "r4", "currentR4"):
            is_new = name == "currentR4"
            g = new["rows"][n] if is_new else old["rows"][n][name]
            g["point"].update(dict(zip(("close", "dif", "dea", "hist"), source[n][1:5])))
            decision = g["decision"]
            decision.update(rawSign=(source[n][4] > 0) - (source[n][4] < 0), wave=deepcopy(waves[n]))
            decision["before"]["wave"] = deepcopy(waves[n-1]) if n else None
            decision["turn"]["currentDif"] = source[n][2]
            decision["turn"]["previousDif"] = source[n-1][2] if n else None
            decision["referenceChecks"] = []
            if n >= 6:
                observed = dict(stage="not_entered", candidate="B", wave=deepcopy(WAVES[3]),
                                checked=False, pricePassed=None, difPassed=None, reason="未检查")
                observed.update({"referenceBroken": None} if is_new else {"reference": deepcopy(ref)})
                decision["referenceChecks"] = [observed]
            if n < 7:
                continue
            state = "DULL" if n == 7 or is_new and n == 9 else "STRUCTURE" if n == 8 else "NONE"
            g["point"].update(ordinaryState=state, ordinaryDirection="BOTTOM" if state != "NONE" else None,
                              activeReference=deepcopy(new_ref if is_new else ref) if state != "NONE" else None)
            if is_new:
                decision["referenceAfter"] = g["point"]["activeReference"]
            else:
                decision["selectedReference"] = None if state == "NONE" else dict(
                    reference=deepcopy(ref), startedAt=DAYS[7], action="activation" if n == 7 else "retained", rearmId=None)
            event_id = name + ("-dull" if n == 7 else "-structure" if n == 8 else "-return")
            e = dict(id=event_id, time=DAYS[n], direction="BOTTOM", type="DULL" if n == 7 else "STRUCTURE" if n == 8 else "DULL" if is_new else "STRUCTURE_DISAPPEARED",
                     route="activation" if n == 7 else "dif_turn" if n == 8 else "dif_return",
                     fromState="NONE" if n == 7 else "DULL" if n == 8 else "STRUCTURE",
                     eventReference=deepcopy(new_ref if is_new else ref))
            if is_new:
                e["relatedStructureId"] = "new-bottom" if n >= 8 else None
            else:
                e.update(relatedTopHistoryId=None, relatedBottomHistoryId=name + "-bottom" if n >= 8 else None,
                         relatedRearmId=name + "-wait" if n == 9 else None)
            g["events"] = [e]
            decision["branch"] = e["route"]
            if n >= 8:
                decision["before"].update(state="DULL" if n == 8 else "STRUCTURE", reference=deepcopy(new_ref if is_new else ref))
                decision["turn"].update(checked=True, threshold=0.05 if n == 8 else 0.06, referenceBroken=False)
                if is_new:
                    r = dict(id="new-bottom", direction="BOTTOM", structureEventId="currentR4-structure",
                             formedAt=DAYS[8], formationRoute="dif_turn", originSegmentStart=DAYS[6],
                             originalReference=deepcopy(new_ref), priceExtreme=96.0, priceExtremeAt=DAYS[6],
                             status="ASSESSING" if n == 8 else "DISAPPEARED", lockedAt=None,
                             disappearedAt=None if n == 8 else DAYS[9], disappearanceReason=None if n == 8 else "dif_return")
                    g["structures"] = [r]
                    g["point"]["activeStructureId"] = "new-bottom" if n == 8 else None
                    decision.update(structureId="new-bottom", structureStatus=r["status"])
                else:
                    history = dict(id=name + "-bottom", structureEventId=name + "-structure", confirmedAt=DAYS[8],
                                   confirmationRoute="dif_turn", originSegmentStart=DAYS[6], leftOriginAt=None,
                                   priceLow=96.0, priceLowAt=DAYS[6], originalReference=deepcopy(ref), status="PENDING" if n == 8 else "ENDED",
                                   endedAt=None if n == 8 else DAYS[9], endReason=None if n == 8 else "structure_disappeared",
                                   observedThrough=DAYS[n], ageBars=n-8)
                    g["bottomHistories"] = [history]
                    g["point"]["pendingBottomHistoryId"] = name + "-bottom" if n == 8 else None
                    if n == 9:
                        waiting = dict(id=name + "-wait", direction="BOTTOM", bottomHistoryId=name + "-bottom", structureEventId=name + "-structure",
                                       structureConfirmedAt=DAYS[8], structureRoute="dif_turn", segmentStart=DAYS[6], nearestPriceGate=98.0,
                                       referenceWave=deepcopy(WAVES[3]), disappearedAt=DAYS[9], observedThrough=DAYS[9], status="WAITING", endedAt=None, endReason=None)
                        g["rearmRecords"] = [waiting]
                        g["point"]["pendingRearmId"] = waiting["id"]
    return old, new, tuple(source)


def test_hc15_old_waiting_remains_waiting_and_new_return_is_dull():
    old, new, source = bottom_wait_ledgers()
    result = module.compare_fact_groups(old, new, input_rows=source, check=lambda: None)
    day = next(row for row in result["differenceDays"] if row["time"] == DAYS[9])
