def test_checks_are_called_during_comparison_and_report_and_inputs_are_unchanged():
    old, new = ledgers(length=10, dull=True)
    frozen = deepcopy((old, new))
    calls = []
    result = compare(old, new, 10, check=lambda: calls.append(1))
    assert len(calls) >= 30
    assert (old, new) == frozen
    class Cancelled(RuntimeError): pass
    def cancel(): raise Cancelled()
    with pytest.raises(Cancelled):
        compare(old, new, 10, check=cancel)
    with pytest.raises(Cancelled):
        module.format_report({"metadata": {}, **result}, check=cancel)


def test_actual_fixed_workers_literal_input_links_and_dates():
    """Only twelve hand-written bars, not the real 922-row reader or baseline."""
    from scripts.research.index_market.xxm.r4_history_comparison import (
        ResearchBudget, read_git_sources, run_worker,
    )
    budget = ResearchBudget()
    sources = read_git_sources(budget)
    old = run_worker("OLD_PAIR", INPUT, sources["OLD_PAIR"], budget)
    new = run_worker("CURRENT", INPUT, sources["CURRENT"], budget)
    result = compare(old, new, check=budget.check)
    for name in ("r2", "r4"):
        ordinary = [(row["time"], e["type"]) for row in old["rows"] for e in row[name]["events"]
                    if e["type"] != "RESEARCH_HISTORICAL_WITHDRAWAL"]
