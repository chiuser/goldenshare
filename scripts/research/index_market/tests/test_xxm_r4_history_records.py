    source[DAYS[4]] = (DAYS[4], 102.0, 15.0, 14.0, 2.0, True)
    index = module._Index("r4", False, source)
    observed = deepcopy(WAVES[5])
    observed["dif_at"] = DAYS[4]  # Both d4 and d5 have DIF=15, but producer chose d4.
