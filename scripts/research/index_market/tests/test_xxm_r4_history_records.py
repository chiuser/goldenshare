def wave(sign, start, end, count, price, dif, price_at, dif_at):
    return dict(sign=sign, start=DAYS[start], end=DAYS[end], count=count,
                price=price, dif=dif, price_at=DAYS[price_at], dif_at=DAYS[dif_at])


# Each entry is hand calculated, rather than generated by any wave scanner.
WAVES = (
    wave(1, 0, 0, 1, 100.0, 20.0, 0, 0), wave(1, 0, 1, 2, 101.0, 21.0, 1, 1),
    wave(-1, 2, 2, 1, 98.0, 5.0, 2, 2), wave(-1, 2, 3, 2, 98.0, 4.0, 2, 3),
    wave(1, 4, 4, 1, 102.0, 14.0, 4, 4), wave(1, 4, 5, 2, 103.0, 15.0, 5, 5),
    wave(-1, 6, 6, 1, 100.0, 6.0, 6, 6), wave(-1, 6, 7, 2, 100.0, 5.0, 6, 7),
    wave(1, 8, 8, 1, 104.0, 13.0, 8, 8), wave(1, 8, 9, 2, 105.0, 14.0, 9, 9),
    wave(1, 8, 10, 3, 106.0, 14.0, 10, 9), wave(-1, 11, 11, 1, 104.0, 14.0, 11, 11))


def reference(which="B", *, current=False):
    w = WAVES[1 if which == "A" else 5]
    result = {"startTime": w["start"], "endTime": w["end"], "price": w["price"], "dif": w["dif"]}
    if current:
        result.update(priceAt=w["price_at"], difAt=w["dif_at"])
    return result


def event(name, n, kind, *, current=False, route="activation", reference_name="B", related=None):
    item = dict(id=name, time=DAYS[n], direction="TOP", type=kind, route=route,
                fromState="NONE" if kind == "DULL" else "DULL", eventReference=reference(reference_name, current=current))
    if current:
        item["relatedStructureId"] = related
    else:
        item.update(relatedTopHistoryId=related, relatedBottomHistoryId=None, relatedRearmId=None)
    return item


def group(n, name, *, current=False, state="NONE", ref="B", events=(), structures=(), histories=(), active=None):
    stamp = DAYS[n]
    point = dict(zip(("time", "close", "dif", "dea", "hist"), INPUT[n][:5]))
    point.update(ordinaryState=state, ordinaryDirection=None if state == "NONE" else "TOP",
                 activeReference=reference(ref, current=current) if state != "NONE" else None)
    before = dict(state="NONE", reference=None, wave=deepcopy(WAVES[n-1]) if n else None)
    checks = []
    if n >= 8:
        for which in ("B", "A"):
            item = dict(stage="not_entered", candidate=which, wave=deepcopy(WAVES[5 if which == "B" else 1]),
                        checked=False, pricePassed=None, difPassed=None, reason="未调用选择方法")
            if current:
                item["referenceBroken"] = None
            else:
                item["reference"] = reference(which)
            checks.append(item)
    turn = dict(previousDif=INPUT[n-1][2] if n else None, currentDif=INPUT[n][2], threshold=None,
                referenceBroken=None, checked=False, reason="未检查")
    decision = dict(before=before, rawSign=(point["hist"] > 0) - (point["hist"] < 0),
                    wave=deepcopy(WAVES[n]), referenceChecks=checks, turn=turn,
                    branch="activation" if events and events[0]["route"] == "activation" else "no_activation",
                    reason="人工逐根记录")
    if current:
        point["activeStructureId"] = active
        before.update(previousDif=INPUT[n-1][2] if n else None, activeStructureId=None)
        decision.update(time=stamp, referenceAfter=point["activeReference"], selectionCalls=[], switched=False,
                        structureId=structures[-1]["id"] if structures else None,
                        structureStatus=structures[-1]["status"] if structures else None)
        return dict(time=stamp, point=point, events=list(events), structures=list(structures), decision=decision)
    point.update(pendingTopHistoryId=active, pendingBottomHistoryId=None, pendingRearmId=None)
    before.update(previous=dict(zip(("time", "close", "dif", "dea", "hist", "completed"), INPUT[n-1])) if n else None,
                  pendingRearm=None)
    decision.update(countMeaning="旧色段根数", selectedReference=None if state == "NONE" else {
        "reference": reference(ref), "startedAt": DAYS[9], "action": "activation", "rearmId": None})
    return dict(point=point, events=list(events), histories=list(histories), bottomHistories=[], rearmRecords=[], decision=decision)


def ledgers(*, length=12, dull=False, reference_by_group=None):
    references = {"r2": "B", "r4": "B", "currentR4": "B", **(reference_by_group or {})}
    old_rows, new_rows = [], []
    for n in range(length):
        old = dict(time=DAYS[n], input=dict(zip(("time", "close", "dif", "dea", "hist", "completed"), INPUT[n])))
        for name in ("r2", "r4", "currentR4"):
            current = name == "currentR4"
            active = dull and n == 9
            events = [event(name + "dull", n, "DULL", current=current, reference_name=references[name])] if active else []
            g = group(n, name, current=current, state="DULL" if active else "NONE", ref=references[name], events=events)
            if current:
                new_rows.append(g)
            else:
                old[name] = g
        old_rows.append(old)
    return dict(metadata={}, rows=old_rows, summary={}), dict(identity={}, rows=new_rows)


def compare(old, new, length=12, check=lambda: None):
    return module.compare_fact_groups(old, new, input_rows=INPUT[:length], check=check)


def test_hc13_identical_literal_facts_have_zero_dates_and_none_first():
    old, new = ledgers(length=1)
    frozen = deepcopy((old, new))
    result = compare(old, new, 1)
    assert result["summary"]["differenceDateCount"] == 0
    assert result["summary"]["differenceDates"] == []
    assert result["summary"]["firstDifference"] is None
    assert result["differenceDays"] == []
    assert (old, new) == frozen


