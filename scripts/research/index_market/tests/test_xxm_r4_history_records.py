def test_hc14_same_key_tied_dif_dates_conflict_instead_of_guessing():
    source = {row[0]: row for row in INPUT}
    source[DAYS[4]] = (DAYS[4], 102.0, 15.0, 14.0, 2.0, True)
    index = module._Index("r4", False, source)
    observed = deepcopy(WAVES[5])
    observed["dif_at"] = DAYS[4]  # Both d4 and d5 have DIF=15, but producer chose d4.
    index.wave(observed, DAYS[8], remember=True)
    index.wave(observed, DAYS[9], remember=True)
    assert index.reference(reference(), DAYS[9])["difAt"] == DAYS[4]
    conflicting = deepcopy(observed)
    conflicting["dif_at"] = DAYS[5]
    with pytest.raises(ValueError, match="冲突极值日期"):
        index.wave(conflicting, DAYS[9], remember=True)


