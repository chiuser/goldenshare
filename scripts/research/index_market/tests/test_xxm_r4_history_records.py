@pytest.mark.parametrize("mutation", ["missing", "conflicting", "wrong_value", "future", "wrong_group"])
def test_hc14_old_reference_dates_must_come_from_same_group_wave(mutation):
    old, new = ledgers(length=10, dull=True)
    g = old["rows"][9]["r4"]
    if mutation == "missing":
        for r in old["rows"]:
            r["r4"]["decision"]["referenceChecks"] = []
    elif mutation == "conflicting":
        g["decision"]["referenceChecks"][0]["wave"]["dif_at"] = DAYS[4]
    elif mutation == "wrong_value":
        g["point"]["activeReference"]["dif"] = 999.0
    elif mutation == "future":
        g["decision"]["referenceChecks"][0]["wave"]["end"] = DAYS[11]
    else:
        for r in old["rows"]:
            r["r4"]["decision"]["referenceChecks"] = []
        assert old["rows"][9]["r2"]["decision"]["referenceChecks"]
    with pytest.raises(ValueError):
        compare(old, new, 10)


