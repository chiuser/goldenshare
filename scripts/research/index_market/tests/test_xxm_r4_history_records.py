    assert day["groups"]["currentR4"]["point"]["ordinaryState"] == "DULL"
    assert day["groups"]["currentR4"]["structures"][0]["status"] == "DISAPPEARED"
    assert day["groups"]["currentR4"]["events"][0]["type"] == "DULL"
    assert "STRUCTURE_DISAPPEARED" in module.format_report({"metadata": {}, **result}, check=lambda: None)


