def test_hc17_handwritten_small_counts_accept_and_reject_one_change():
    old = {"rows": [{"r2": {"events": [{"type": "DULL"}]}, "r4": {"events": [{"type": "DULL"}]}}],
           "summary": {"r2EventCounts": {"DULL": 1}, "r4EventCounts": {"DULL": 1}}}
    checks = module._validate_event_counts(old, {"DULL": 1}, lambda: None)
    assert len(checks) == 4
    assert checks[0] == {"name": "r2EventCounts", "expected": {"DULL": 1}, "actual": {"DULL": 1}}
    old["summary"]["r4EventCounts"]["DULL"] = 2
    with pytest.raises(ValueError, match="r4SummaryEventCounts"):
        module._validate_event_counts(old, {"DULL": 1}, lambda: None)


