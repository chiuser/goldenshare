from datetime import date, timedelta

import pytest

from scripts.research.index_market.xxm.cancellation_restart_audit import RestartAudit, replay, run
from src.biz.services.wealth.market.index_detail_xxm.types import XxmBar


def bar(n, hist=-2):
    return XxmBar((date(2020, 1, 1) + timedelta(days=n)).isoformat(), 100, -5, -5 - hist / 2, hist)


def event(kind, route="dif_break", ref=-10, direction="BOTTOM"):
    return dict(type=kind, route=route, direction=direction,
        eventReference=dict(startTime="2019-01-01", endTime="2019-01-02", price=90, dif=ref))


def test_true_cancel_then_dull_without_red_is_a_counterexample():
    audit = RestartAudit()
    audit.observe(bar(0), [event("CANCEL")])
    audit.observe(bar(1), [])
    audit.observe(bar(2), [event("DULL", "activation", -30)])
    episode, = audit.episodes
    assert episode["status"] == "RESTART_BEFORE_RED"
    assert episode["sameContinuousGreen"] is True
    assert episode["referenceChanged"] is True
    assert episode["negativeBarsAtRestart"] == 3


def test_zero_is_not_a_red_column_or_a_continuous_green_segment():
    audit = RestartAudit()
    audit.observe(bar(0), [event("CANCEL")])
    audit.observe(bar(1, 0), [])
    audit.observe(bar(2), [])
    audit.observe(bar(3), [event("DULL", "activation")])
    episode, = audit.episodes
    assert episode["status"] == "RESTART_BEFORE_RED"
    assert episode["firstZeroAt"] == "2020-01-02"
    assert episode["sameContinuousGreen"] is False
    assert episode["negativeBarsAtRestart"] == 2


def test_red_on_cancellation_endpoint_counts_and_new_green_streak_is_independent():
    audit = RestartAudit()
    audit.observe(bar(0, 2), [event("CANCEL", "dif_break_on_flip")])
    audit.observe(bar(1), [])
    audit.observe(bar(2), [event("DULL", "activation")])
    episode, = audit.episodes
    assert episode["status"] == "RESTART_AFTER_RED"
    assert episode["firstRedAt"] == "2020-01-01"
    assert episode["negativeBarsAtRestart"] == 2
    assert episode["referenceChanged"] is False


def test_structure_disappearance_history_green_and_top_cancel_do_not_open_episode():
    audit = RestartAudit()
    audit.observe(bar(0), [event("STRUCTURE_DISAPPEARED", "dif_return")])
    audit.observe(bar(1), [event("RESEARCH_HISTORICAL_WITHDRAWAL", "historical_price_break")])
    audit.observe(bar(2), [event("CANCEL", direction="TOP")])
    audit.observe(bar(3), [event("DULL", "reactivation")])
    assert audit.episodes == []
    assert dict(audit.excluded) == {"STRUCTURE_DISAPPEARED": 1, "RESEARCH_HISTORICAL_WITHDRAWAL": 1}


def test_unfinished_episode_remains_right_censored_even_when_red_arrives():
    audit = RestartAudit()
    audit.observe(bar(0), [event("CANCEL")])
    audit.observe(bar(1, 2), [])
    assert audit.episodes[0]["status"] == "RIGHT_CENSORED"
    assert audit.episodes[0]["nextDull"] is None
    assert audit.episodes[0]["observedThrough"] == "2020-01-02"


def test_first_dull_closes_episode_and_later_dull_cannot_replace_it():
    audit = RestartAudit()
    audit.observe(bar(0), [event("CANCEL")])
    audit.observe(bar(1), [event("DULL", "activation", -30)])
    audit.observe(bar(2, 2), [])
    audit.observe(bar(3), [event("DULL", "activation", -40)])
    assert audit.episodes[0]["nextDull"]["bar"]["time"] == "2020-01-02"
    assert audit.episodes[0]["status"] == "RESTART_BEFORE_RED"


def test_unknown_route_duplicate_time_and_consecutive_cancel_are_rejected():
    with pytest.raises(ValueError, match="route"):
        RestartAudit().observe(bar(0), [event("CANCEL", "invented")])
    audit = RestartAudit()
    audit.observe(bar(0), [event("CANCEL")])
    with pytest.raises(ValueError, match="ordered"):
        audit.observe(bar(0), [])
    with pytest.raises(ValueError, match="Second"):
        audit.observe(bar(1), [event("CANCEL")])


def test_manually_traceable_two_reference_switch_and_exhaustion():
    # Stronger old low: price80/DIF-30, nearer weak low: price90/DIF-10.
    # price88 breaks only90 -> weak DULL; DIF-11 invalidates -10.
    # Later price79 breaks80 while DIF-12 still above -30 -> new DULL.
    # Then DIF-31 invalidates both; later DIF rebound cannot undo segment min.
    values = [(80, -30, -2), (100, 0, 2), (90, -10, -2), (100, 0, 2),
        (89, -5, -2), (88, -6, -2), (85, -11, -2), (79, -12, -2),
        (77, -31, -2), (70, -29, -2), (69, -28, -2)]
    bars = [XxmBar((date(2020, 1, 1) + timedelta(days=i)).isoformat(), c, d, d - h / 2, h)
        for i, (c, d, h) in enumerate(values)]
    audit, events, _ = replay("day", bars)
    assert [(e["time"], e["type"], e["eventReference"]["dif"]) for e in events] == [
        ("2020-01-06", "DULL", -10), ("2020-01-07", "CANCEL", -10),
        ("2020-01-08", "DULL", -30), ("2020-01-09", "CANCEL", -30)]
    assert [e["status"] for e in audit.episodes] == ["RESTART_BEFORE_RED", "RIGHT_CENSORED"]
    assert audit.episodes[0]["nextDull"]["context"]["wave"]["dif"] == -12


def test_reference_lock_delays_switch_even_when_stronger_price_gate_is_already_met():
    # Strong old80/-30 is unavailable at weak activation price88.
    # price79 becomes eligible while the weak reference remains locked.
    # Approved R1: switch at its actual DIF break (-11) without CANCEL/new DULL;
    # the source test still expected the retired pre-R1 cancellation sequence.
    values = [(80, -30, -2), (100, 0, 2), (90, -10, -2), (100, 0, 2),
        (89, -5, -2), (88, -6, -2), (79, -7, -2), (78, -11, -2), (77, -12, -2)]
    bars = [XxmBar((date(2020, 1, 1) + timedelta(days=i)).isoformat(), c, d, d - h / 2, h)
        for i, (c, d, h) in enumerate(values)]
    audit, events, _ = replay("day", bars)
    assert [(e["time"], e["type"], e["eventReference"]["dif"]) for e in events] == [
        ("2020-01-06", "DULL", -10)]
    assert not audit.episodes
    # Independent literal reference path, also covered by R1 product tests.
    from src.biz.services.wealth.market.index_detail_xxm.calculator import XxmCalculator
    calc=XxmCalculator(period='day',source_identity='literal-reference-path')
    selected=[]
    for value in bars:
        calc.step(value);selected.append(calc.reference.dif if calc.reference else None)
    assert selected[5:]==[-10,-10,-30,-30]


