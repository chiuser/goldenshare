@pytest.mark.parametrize("execution", ["2026-10-16", "2026-10-17"])
def test_first_manual_precheck_has_no_parent_or_bootstrap_reads(
    tmp_path, monkeypatch, execution
):
    with isolated_update_environment(tmp_path, monkeypatch) as env:
        instance, job, source, lake, _, counts = env
        input_files(tmp_path, lake, changed=())
        downloader = source(())
        monkeypatch.setattr(
            asset, "_now", lambda: datetime.fromisoformat(execution + "T10:00:00+08:00")
        )
        monkeypatch.setattr(
            asset,
            "raw_tushare_adj_factor_ready_for_trade_date",
            lambda *_: SimpleNamespace(ready=False, reason="test waiting"),
        )
        with patch.object(
            asset.initialization,
            "load_stk_factor_pro_bootstrap_supplement_authorization",
        ) as authorization:
            executed = job.execute_in_process(
                instance=instance,
                partition_key=str(PREVIOUS),
                run_config=config(
                    PREVIOUS,
                    execution_day=date.fromisoformat(execution),
                    purpose="manual_date",
                    slot=None,
                ),
            )
        assert executed.success
        run = instance.get_run_by_id(executed.run_id)
        assert run.parent_run_id is None and run.root_run_id is None
        assert not authorization.called and not counts["initialization"]
        assert not downloader.calls and not executed.get_asset_materialization_events()
        (observation,) = executed.get_asset_observation_events()
        values = C.parse_stk_factor_pro_observation_metadata(
            observation.asset_observation_data.asset_observation.metadata
        )
        assert values["purpose"] == "manual_date" and values["scheduled_slot"] is None
        assert values["execution_day"] == date.fromisoformat(execution)
        assert values["target_trade_date"] == PREVIOUS
        assert "submission_no" not in values and "business_attempt" not in values
        assert values["observation_kind"] == "precheck"


@pytest.mark.parametrize("reason", ["missing_previous", "wrong_submission_day"])
def test_manual_precheck_rejects_before_download_or_plan(tmp_path, monkeypatch, reason):
    with isolated_update_environment(tmp_path, monkeypatch) as env:
        instance, job, source, lake, staging, _ = env
        input_files(tmp_path, lake, changed=())
        downloader = source(())
        target = PREVIOUS
        if reason == "missing_previous":
            target = date(2026, 10, 16)
            with connection(tmp_path) as conn:
                parquet(
                    conn,
                    silver_trade_calendar_path(lake),
                    SILVER_TRADE_CALENDAR_SCHEMA,
                    [
                        ("SSE", date(2026, 10, 13), True, date(2026, 10, 12)),
                        ("SSE", date(2026, 10, 14), True, date(2026, 10, 13)),
                        ("SSE", target, True, PREVIOUS),
                    ],
                )
        monkeypatch.setattr(
            asset, "_now", lambda: datetime.fromisoformat("2026-10-17T10:00:00+08:00")
        )
        executed = job.execute_in_process(
            instance=instance,
            partition_key=str(target),
            run_config=config(
                target,
                execution_day=date(2026, 10, 17)
                if reason == "missing_previous"
                else date(2026, 10, 16),
                purpose="manual_date",
                slot=None,
            ),
            raise_on_error=False,
        )
        assert not executed.success
        failure = executed.get_run_failure_event()
        assert failure
        message = executed.get_step_failure_events()[
            0
        ].step_failure_data.error.to_string()
        assert (
            "pretrade_date" if reason == "missing_previous" else "本次上海日期"
        ) in message
        assert not downloader.calls and not executed.get_asset_materialization_events()
        assert not (staging / "stk_factor_pro").exists()


