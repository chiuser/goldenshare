NOV5, NOV6, NOV9, NOV10, NOV11 = (date(2026, 11, n) for n in (5, 6, 9, 10, 11))
CALENDAR = {NOV5: None, NOV6: NOV5, NOV9: NOV6, NOV10: NOV9, NOV11: NOV10}
SEVEN_FIELDS = (
    "execution_day",
    "target_trade_date",
    "purpose",
    "scheduled_slot",
    "bootstrap_operation_id",
    "expected_bootstrap_approval_digest",
    "expected_bootstrap_date_result_digest",
)


def manual_config(execution="2026-11-11", target="2026-11-10", **overrides):
    return {
        "execution_day": execution,
        "target_trade_date": target,
        "purpose": "manual_date",
        "scheduled_slot": None,
        **overrides,
    }


@pytest.mark.parametrize("execution", ["2026-11-11", "2026-11-14"])
def test_manual_date_literal_dates_and_native_schema(execution):
    @dg.op(name="stk_factor_pro", config_schema=C.STK_FACTOR_PRO_UPDATE_CONFIG_SCHEMA)
    def operation():
        pass

    @dg.job
    def job():
        operation()

    validated = dg.validate_run_config(
        job, {"ops": {"stk_factor_pro": {"config": manual_config(execution)}}}
    )["ops"]["stk_factor_pro"]["config"]
    assert tuple(C.STK_FACTOR_PRO_UPDATE_CONFIG_SCHEMA) == SEVEN_FIELDS
    assert set(validated) == set(SEVEN_FIELDS)
    assert all(validated[name] is None for name in SEVEN_FIELDS[3:])
    parsed = C.parse_stk_factor_pro_run_input(validated, "2026-11-10", CALENDAR)
    assert tuple(f.name for f in fields(parsed)) == SEVEN_FIELDS
    assert parsed.execution_day == date.fromisoformat(execution)
    assert parsed.target_trade_date == NOV10 and parsed.purpose == "manual_date"


