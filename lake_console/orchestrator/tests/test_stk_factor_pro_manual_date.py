@pytest.mark.parametrize(
    "kind", ["valid", "missing", "closed", "same", "future", "null", "target_closed"]
)
def test_producer_shaped_calendar_requires_exact_pretrade_date(tmp_path, kind):
    # Monday must refer to Friday, even if Thursday exists in the file.
    previous = (
        NOV9
        if kind == "same"
        else NOV10
        if kind == "future"
        else None
        if kind == "null"
        else NOV6
    )
    rows = [("SSE", NOV5, True, None), ("SSE", NOV9, kind != "target_closed", previous)]
    if kind != "missing":
        rows.append(("SSE", NOV6, kind != "closed", NOV5))
    if kind == "future":
        rows.append(("SSE", NOV10, True, NOV9))
    # Another exchange cannot supply SSE's missing Friday.
    rows.append(("SZSE", NOV6, True, NOV5))
    with connection(tmp_path) as conn:
        parquet(
            conn,
            silver_trade_calendar_path(tmp_path),
            SILVER_TRADE_CALENDAR_SCHEMA,
            rows,
        )
        calendar = asset._open_calendar(conn, tmp_path, {}, {})
        value = manual_config(target="2026-11-09")
        if kind == "valid":
            parsed = C.parse_stk_factor_pro_run_input(value, "2026-11-09", calendar)
            assert parsed.target_trade_date == NOV9
            assert C.stk_factor_pro_previous_trade_date(calendar, NOV9) == NOV6
        else:
            with pytest.raises(ValueError, match="pretrade_date"):
                C.parse_stk_factor_pro_run_input(value, "2026-11-09", calendar)


