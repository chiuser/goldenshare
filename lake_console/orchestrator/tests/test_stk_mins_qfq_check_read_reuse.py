def gold_row(**changes):
    row = {
        "ts_code": CODE,
        "freq": 1,
        "trade_date": DAY,
        "trade_time": f"{DAY} 10:00:00",
        "open": 10.0,
        "high": 12.0,
        "low": 9.0,
        "close": 11.0,
        "vol": 100.0,
        "amount": 1000.0,
        "exchange": "SSE",
    }
    row.update(changes)
    return row


def write_rows(path, rows, *, schema=GOLD_STK_MINS_QFQ_SCHEMA, omit=(), types=None):
    path.parent.mkdir(parents=True, exist_ok=True)
    columns = [
        (c.name, (types or {}).get(c.name, c.type))
        for c in schema
        if c.name not in omit
    ]
    with duckdb.connect() as connection:
        connection.execute(
            "CREATE TABLE sample_rows ("
            + ",".join(f'"{n}" {t}' for n, t in columns)
            + ")"
        )
        if rows:
            connection.executemany(
                "INSERT INTO sample_rows VALUES ("
                + ",".join("?" for _ in columns)
                + ")",
                [[r.get(n) for n, _ in columns] for r in rows],
            )
        connection.execute(
            f"COPY sample_rows TO {duckdb_string(path)} (FORMAT PARQUET)"
        )


class RecordedConnection:
    def __init__(self, connection, statements):
        self.connection = connection
        self.statements = statements

    def execute(self, sql, *args, **kwargs):
        self.statements.append(sql)
        self.connection.execute(sql, *args, **kwargs)
        return self

    def __getattr__(self, name):
        return getattr(self.connection, name)


@pytest.fixture
def isolated_connection(tmp_path, monkeypatch):
    directory = tmp_path / "duckdb"
    directory.mkdir()
    settings = DuckDBConnectionSettings(temp_directory=directory)
    statements = []
    policies = []

    @contextmanager
    def factory(*, temp_policy="managed"):
        policies.append(temp_policy)
        with connect_configured_duckdb(settings, temp_policy=temp_policy) as connection:
            yield RecordedConnection(connection, statements)

    monkeypatch.setattr(checks, "connect_configured_duckdb", factory)
    return factory, statements, policies, directory


def expectation_sql(rows):
    values = ",".join(
        "("
        + ",".join("NULL" if value is None else duckdb_string(value) for value in row)
        + ")"
        for row in rows
    )
    if not values:
        return "SELECT NULL::VARCHAR ts_code, NULL::DATE trade_date, NULL::TIMESTAMP trade_time, NULL::VARCHAR exchange WHERE false"
    return f"SELECT CAST(code AS VARCHAR) ts_code, CAST(day AS DATE) trade_date, CAST(time AS TIMESTAMP) trade_time, CAST(exchange AS VARCHAR) exchange FROM (VALUES {values}) e(code,day,time,exchange)"


def run_file_check(connection, paths, expected=()):
    return checks._gold_qfq_formal_file_counts(
        connection,
        paths=paths,
        partition_key=DAY,
        freq=1,
        expected_identity_sql=expectation_sql(expected),
    )


def gold_path(root, code=CODE, year="2026"):
    return gold_stk_mins_qfq_path(root, 1, code, year)


def data_reads(statements, path):
    return [
        sql
        for sql in statements
        if "read_parquet(" in sql
        and str(path) in sql
        and not sql.lstrip().upper().startswith("DESCRIBE")
    ]


