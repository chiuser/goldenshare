@pytest.mark.parametrize(
    "heterogeneous",
    ["missing_close", "promote_close", "empty", "unused_invalid_amount"],
)
def test_union_schema_matches_original_reader(
    tmp_path, isolated_connection, heterogeneous
):
    factory, _, _, _ = isolated_connection
    first, second = gold_path(tmp_path), gold_path(tmp_path, "000001.SZ")
    write_rows(first, [gold_row()])
    write_rows(
        second,
        []
        if heterogeneous == "empty"
        else [
            gold_row(
                ts_code="000001.SZ",
                close=11,
                **(
                    {"amount": "unused invalid value"}
                    if heterogeneous == "unused_invalid_amount"
                    else {}
                ),
            )
        ],
        omit=("close",) if heterogeneous == "missing_close" else (),
        types={"close": "VARCHAR"}
        if heterogeneous == "promote_close"
        else {"amount": "VARCHAR"}
        if heterogeneous == "unused_invalid_amount"
        else None,
    )
    paths = [first, second]
    expected = [
        (CODE, DAY, f"{DAY} 10:00:00", "SSE"),
        ("000001.SZ", DAY, f"{DAY} 10:00:00", "SSE"),
    ]
    with factory(temp_policy="existing_no_spill") as connection:
        source = checks._read_parquet_paths(paths, filename=True)
        legacy_counts = connection.execute(
            minute_qfq_counts_sql(gold_source=source, partition_key=DAY, freq=1)
        ).fetchone()
        legacy_identity = connection.execute(
            minute_qfq_identity_coverage_counts_sql(
                gold_source=source,
                expected_identity_sql=expectation_sql(expected),
                partition_key=DAY,
            )
        ).fetchone()
        observed, _ = run_file_check(connection, paths, expected)
    literal = (
        (1, 0, 0, 0, 1, 0, 0)
        if heterogeneous == "empty"
        else (2, 0, 0, int(heterogeneous == "missing_close"), 0, 0, 0)
    )
    assert observed == literal
    assert observed == (*legacy_counts, *legacy_identity)


def test_failed_samples_keep_original_global_order_and_limit(
    tmp_path, isolated_connection
):
    factory, statements, _, _ = isolated_connection
    paths = [gold_path(tmp_path, "000001.SZ"), gold_path(tmp_path)]
    for index, path in enumerate(paths):
        write_rows(
            path,
            [
                gold_row(
                    ts_code="bad",
                    freq=5,
                    trade_time=f"{DAY} 10:{minute:02}:00",
                    open=-1.0,
                )
                for minute in range(9 - index, 2 - index, -1)
            ],
        )
    with factory(temp_policy="existing_no_spill") as connection:
        relation = checks._read_parquet_paths(paths, filename=True)
        original = {}
        for name, sql in checks._gold_qfq_sample_queries(
            gold_source=relation, partition_key=DAY, freq=1
        ).items():
            rows = connection.execute(sql).fetchall()
            original[name] = checks._sample_dicts(
                [c[0] for c in connection.description], rows
            )
        statements.clear()
        counts, samples = run_file_check(connection, paths)
    assert counts[:4] == (14, 14, 6, 14)
    assert samples == original
    assert all(len(data_reads(statements, path)) == 1 for path in paths)


