def test_input_changes_are_rejected(tmp_path, isolated_connection, monkeypatch):
    factory, _, _, _ = isolated_connection
    target = gold_path(tmp_path)
    write_rows(target, [gold_row()])
    actual = checks._qfq_check_file_identity
    calls = 0

    def changed(path):
        nonlocal calls
        calls += 1
        identity = actual(path)
        return (*identity[:-1], identity[-1] + 1) if calls >= 3 else identity

    monkeypatch.setattr(checks, "_qfq_check_file_identity", changed)
    with (
        factory(temp_policy="existing_no_spill") as connection,
        pytest.raises(ValueError, match="input changed"),
    ):
        run_file_check(connection, [target])


